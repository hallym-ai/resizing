import assert from 'node:assert/strict';
import {verifyPhotoPartition,verifyExtendedPhotoPartition,inferPhotoFrame} from './photo-composite-recovery.mjs';
const src=new Uint8ClampedArray([10,20,30,255,40,50,60,128,0,0,0,0]);
const bg=new Uint8ClampedArray([10,20,30,255,0,0,0,0,0,0,0,0]);
const fg=new Uint8ClampedArray([0,0,0,0,40,50,60,128,0,0,0,0]);
assert(verifyPhotoPartition(src,bg,fg),'exact ownership with original alpha');
let x=bg.slice();x[0]++;assert(!verifyPhotoPartition(src,x,fg),'source RGB changes are rejected');
x=bg.slice();x[3]=127;assert(!verifyPhotoPartition(src,x,fg),'fractional alpha split is rejected');
x=bg.slice();x[7]=128;assert(!verifyPhotoPartition(src,x,fg),'overlapping parts are rejected');
x=fg.slice();x[7]=0;assert(!verifyPhotoPartition(src,bg,x),'missing foreground is rejected');
x=fg.slice();x[11]=1;assert(!verifyPhotoPartition(src,bg,x),'new content in a transparent original is rejected');
assert(!verifyPhotoPartition(src,bg,new Uint8Array(1)),'mismatched dimensions rejected');
const s=new Uint8ClampedArray([10,20,30,255,40,50,60,128]),f=new Uint8ClampedArray([0,0,0,0,40,50,60,128]);
const frame={x:1,y:1,width:4,height:3},ext=new Uint8ClampedArray(4*3*4);for(let i=3;i<ext.length;i+=4)ext[i]=255;
ext.set([10,20,30,255,0,0,0,0],(1*4+1)*4);
assert(verifyExtendedPhotoPartition(s,ext,f,2,1,frame),'extended frame is an exact partition with opaque external area');
let edited=ext.slice();edited[3]=0;assert(!verifyExtendedPhotoPartition(s,edited,f,2,1,frame),'transparent external area is rejected');
edited=ext.slice();edited[(1*4+1)*4]++;assert(!verifyExtendedPhotoPartition(s,edited,f,2,1,frame),'changed embedded source is rejected');
assert(!verifyExtendedPhotoPartition(s,ext,f,2,1,{...frame,x:0}),'unverified frame position is rejected');
const obj=(width,height,matrix)=>({width,height,calcTransformMatrix:()=>matrix});
const source=obj(2,1,[1,0,0,1,8,9]),background=obj(4,3,[1,0,0,1,8,9]),foreground=obj(2,1,[1,0,0,1,8,9]);
assert.deepEqual(inferPhotoFrame(source,background,foreground),frame,'padding is derived from current transforms');
assert.equal(inferPhotoFrame(source,background,obj(2,1,[1,0,0,1,8.1,9])),null,'relative foreground movement rejects inference');
assert.equal(inferPhotoFrame(source,obj(4,3,[1,0,0,1,8.25,9]),foreground),null,'fractional source-pixel padding is rejected');
assert.equal(inferPhotoFrame(source,obj(4,3,[0,0,0,0,8,9]),foreground),null,'singular transform is rejected');
const huge=[1000000,0,0,1000000,100000000,100000000];
assert.equal(inferPhotoFrame(obj(200,200,huge),obj(202,202,huge),obj(200,200,[1000000,0,0,1000000,100000005,100000000])),null,'large coordinates never mask a visible movement');
assert.deepEqual(inferPhotoFrame(obj(200,200,huge),obj(202,202,huge),obj(200,200,[1000000,0,0,1000000,100000000.000001,100000000])),{x:1,y:1,width:202,height:202},'tiny numeric noise remains supported');
console.log('pass: reopened raw photo must be an exact pixel partition');
